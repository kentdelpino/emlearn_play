/* 
 * This overrides the low-level system write function used by printf().
 * It routes characters sequentially through your SysConfig-defined UART.
 */
int _write(int file, char *ptr, int len) {

  int i;
  for (i = 0; i < len; i++) {
    // Wait until UART TX FIFO is not full before sending next character
    while (DL_UART_isTXFIFOFull(ttyUART_INST));
    // Transmit character
    DL_UART_transmitData(ttyUART_INST, ptr[i]);
  }
  return len;
}

/* 
 * Force unbuffered streams so characters print immediately without waiting for '\n'
*/
void init_printf_unbuffered(void) {
    setvbuf(stdout, NULL, _IONBF, 0);
}

