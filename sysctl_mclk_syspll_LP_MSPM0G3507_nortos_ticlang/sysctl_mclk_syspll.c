void TIMER_0_INST_IRQHandler(void) {

  switch (DL_TimerG_getPendingInterrupt(TIMER_0_INST)) {
    case DL_TIMERG_IIDX_ZERO:
      DL_GPIO_togglePins(GPIO_LEDS_PORT, GPIO_LEDS_USER_LED_1_PIN);
      break;

    default:
      break;
    }
}


